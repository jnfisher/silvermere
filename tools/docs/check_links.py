#!/usr/bin/env python3
"""Check README.md and docs/**/*.md: relative links and #anchors resolve, and every fenced
`bash` block line that starts with `silvermere` names a real subcommand (run with --help).

Lines carrying `TODO(T-0NN)` are the only place a missing link target is allowed.
Usage: python3 tools/docs/check_links.py [--bin PATH]   (default: target/debug/silvermere, else PATH)
"""
import os, re, shlex, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NO_ANCHOR_CHECK = {"docs/schema.md"}  # generated by tools/schema-doc; its in-page links use hyphens
SKIP_DIRS = {"plan", "engine"}  # task cards and generated engine pages are not user docs
LINK = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
FENCE = re.compile(r"^```(\w*)")


def slug(h):
    h = re.sub(r"`", "", h.strip().lower())
    h = re.sub(r"[^\w\- ]", "", h)
    return h.replace(" ", "-")


def anchors(path, cache={}):
    if path not in cache:
        out, fence = set(), False
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("```"):
                fence = not fence
            m = None if fence else re.match(r"#+\s+(.*)", line)
            if m:
                out.add(slug(m.group(1)))
        cache[path] = out
    return cache[path]


def files():
    yield ROOT / "README.md"
    for p in sorted((ROOT / "docs").rglob("*.md")):
        if not SKIP_DIRS & set(p.relative_to(ROOT / "docs").parts[:-1]):
            yield p


def binary(arg):
    if arg:
        return arg
    for c in ("target/debug/silvermere", "target/release/silvermere"):
        if (ROOT / c).exists():
            return str(ROOT / c)
    return "silvermere"


def main():
    exe = binary(sys.argv[sys.argv.index("--bin") + 1] if "--bin" in sys.argv else None)
    errors, checked_cmds = [], set()
    for md in files():
        rel = md.relative_to(ROOT)
        fence = None
        for n, line in enumerate(md.read_text(encoding="utf-8").splitlines(), 1):
            m = FENCE.match(line)
            if m:
                fence = None if fence is not None else m.group(1)
                continue
            if fence is not None:
                if fence == "bash" and line.startswith("silvermere "):
                    words = shlex.split(line.split("#")[0])[1:]
                    sub = [w for w in words if not w.startswith("-")][:1]
                    key = tuple(sub)
                    if sub and key not in checked_cmds:
                        checked_cmds.add(key)
                        r = subprocess.run([exe, *sub, "--help"], capture_output=True)
                        if r.returncode != 0:
                            errors.append(f"{rel}:{n}: `silvermere {sub[0]} --help` failed")
                continue
            if "TODO(T-" in line:
                continue
            for target in LINK.findall(line):
                if re.match(r"[a-z]+:", target):
                    continue
                path, _, frag = target.partition("#")
                dest = (md.parent / path).resolve() if path else md
                if not dest.exists():
                    errors.append(f"{rel}:{n}: missing target {target}")
                elif frag and str(dest.relative_to(ROOT)) not in NO_ANCHOR_CHECK and dest.suffix == ".md" and slug(frag) not in anchors(dest):
                    errors.append(f"{rel}:{n}: missing anchor {target}")
    for e in errors:
        print(e)
    print(f"{len(errors)} problem(s); {len(checked_cmds)} subcommand(s) checked")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
