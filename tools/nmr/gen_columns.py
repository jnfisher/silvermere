#!/usr/bin/env python3
"""Writes crates/silvermere-import/src/nmr/columns.rs from Nightmare Redux's source.

Usage: tools/nmr/gen_columns.py NMR_CHECKOUT > crates/silvermere-import/src/nmr/columns.rs

NMR_CHECKOUT is a clone of https://github.com/mbbsemu/Nightmare-Redux (generated from commit
2aaa47b6240c35bdd13cf568efabbaf309287835). Each record type of
modFieldmaps_vO.bas, its members packed in order (Integer 2, Long 4, Byte 1, String * n n,
arrays (n) holding n + 1), gives each member's offset; each Import* routine of
frmDatabaseImport.frm gives the column its member is assigned from ("For x = a To b" loops
expanded). See docs/import.md, "Nightmare Redux databases".
"""
import re
import sys

SIZES = {"Integer": 2, "Long": 4, "Byte": 1}
TABLES = [
    ("Items", "ImportItems", "ItemRecType", "Itemrec", "ITEMS"),
    ("Rooms", "ImportRooms", "RoomRecType", "Roomrec", "ROOMS"),
    ("Spells", "ImportSpells", "SpellRecType", "Spellrec", "SPELLS"),
    ("Actions", "ImportActions", "ActionRecType", "Actionrec", "ACTIONS"),
    ("Classes", "ImportClasses", "ClassRecType", "Classrec", "CLASSES"),
    ("Races", "ImportRaces", "RaceRecType", "Racerec", "RACES"),
    ("Shops", "ImportShops", "ShopRecType", "Shoprec", "SHOPS"),
    ("Monsters", "ImportMonsters", "MonsterRecType", "Monsterrec", "MONSTERS"),
    ("Messages", "ImportMessages", "MessageRecType", "Messagerec", "MESSAGES"),
]


def members(fieldmaps, name):
    body = re.search(r"Public Type " + name + r"\s*\n(.*?)\nEnd Type", fieldmaps, re.S).group(1)
    off, out = 0, {}
    for line in body.splitlines():
        line = line.split("'")[0].strip()
        if not line:
            continue
        m = re.match(r"(\w+)(?:\((\d+)\))?\s+As\s+(\w+)(?:\s*\*\s*(\d+))?", line)
        member, count, kind, strlen = m.groups()
        size = int(strlen) if kind == "String" else SIZES[kind]
        n = int(count) + 1 if count else 1
        out[member] = (off, size, kind)
        off += size * n
    return out, off


def columns(lines, sub, rec, mems):
    start = next(i for i, l in enumerate(lines) if l.startswith("Private Sub " + sub + "("))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("End Sub"))
    loop, out = None, []
    for line in lines[start:end]:
        s = line.strip()
        if s.startswith("'"):
            continue
        m = re.match(r"For (\w) = (\d+) To (\d+)$", s)
        if m:
            loop = (int(m.group(2)), int(m.group(3)))
            continue
        if re.match(r"Next\b", s):
            loop = None
            continue
        m = re.match(rec + r"\.(\w+)(?:\(([^)]*)\))?\s*=\s*(.+)$", s, re.I)
        if not m or "Fields(" not in m.group(3):
            continue
        member, idx, rhs = m.groups()
        expr = re.match(r"Fields\(((?:[^()]|\([^)]*\))*)\)", rhs[rhs.index("Fields("):]).group(1)
        ulong = rhs.startswith("ULong2SLong")
        looped = loop and (re.search(r"\bx\b", idx or "") or "& x" in expr)
        for x in range(loop[0], loop[1] + 1) if looped else [None]:
            col_expr = expr.replace(" & ", "+")
            if x is not None:
                col_expr = re.sub(r"\bx\b", f"str({x})", col_expr)
            col = eval(col_expr)  # noqa: S307 (VB string literals only)
            i = eval(re.sub(r"\bx\b", str(x), idx)) if idx else 0  # noqa: S307
            off, size, kind = mems[member]
            if kind == "String":
                k = f"Kind::Text({size})"
            elif ulong:
                k = "Kind::ULong"
            else:
                k = {"Integer": "Kind::Integer", "Long": "Kind::Long", "Byte": "Kind::Byte"}[kind]
            out.append(f'    Col::new("{col}", {off + i * size:#06x}, {k}),')
    return out


def main():
    root = sys.argv[1].rstrip("/") + "/"
    fieldmaps = open(root + "modFieldmaps_vO.bas", encoding="latin1").read()
    lines = open(root + "frmDatabaseImport.frm", encoding="latin1").read().splitlines()
    print("""//! The columns of Nightmare Redux's database export and where its import writes them.
//!
//! Generated by `tools/nmr/gen_columns.py` from Nightmare Redux
//! (<https://github.com/mbbsemu/Nightmare-Redux>): the assignments of
//! `frmDatabaseImport.frm` (`ImportItems`, `ImportRooms`, ...) and the record types of
//! `modFieldmaps_vO.bas`, whose members, packed in order, give each one's offset in the
//! Worldgroup 3.x record. Do not edit by hand.

use super::{Col, Kind};
""")
    for table, sub, typ, rec, const in TABLES:
        mems, total = members(fieldmaps, typ)
        print(f"/// `{table}`: NMR's record is {total} bytes.")
        print(f"pub(super) const {const}: &[Col] = &[")
        print("\n".join(columns(lines, sub, rec, mems)))
        print("];\n")


if __name__ == "__main__":
    main()
