#!/usr/bin/env python3
"""Builds the Mudlet mapper package from silvermere-mapper.lua.

    python3 tools/mudlet/build.py          # writes the packages
    python3 tools/mudlet/build.py --check  # fails if a package is out of date

Two files come out, with the same script:

* silvermere-mapper.mpackage, the one players install: a zip of config.lua (the title,
  author, version and description Mudlet's Package Manager shows) and the XML below;
* silvermere-mapper.xml, the bare script, for installing by hand or reading the diff.

The version and date come from `M.version` and `M.released` in the Lua. The zip is built
the same way each time (stored, fixed timestamps and order), so --check can compare bytes.
"""

import io
import re
import sys
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
LUA = HERE / "silvermere-mapper.lua"
XML = HERE / "silvermere-mapper.xml"
MPACKAGE = HERE / "silvermere-mapper.mpackage"

NAME = "silvermere-mapper"

TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE MudletPackage>
<!-- Generated by tools/mudlet/build.py from silvermere-mapper.lua: edit that, then run it. -->
<MudletPackage version="1.001">
	<ScriptPackage>
		<Script isActive="yes" isFolder="no">
			<name>Silvermere mapper</name>
			<packageName>silvermere-mapper</packageName>
			<script>{script}</script>
			<eventHandlerList />
		</Script>
	</ScriptPackage>
</MudletPackage>
"""

TITLE = "Silvermere mapper: draws the map as you walk"

AUTHOR = "Silvermere"

# Markdown, shown in the Package Manager's details.
DESCRIPTION = """\
Draws Mudlet's map from the room data a [Silvermere](https://github.com/jnfisher/silvermere)
server sends over GMCP (`Room.Info`), for MajorMUD played on Silvermere.

* Each room you see is added to the map, in an area per game map (`Map 1`, `Map 2`, ...),
  and linked to the rooms next to it. Exits to rooms you have not been to yet show as stubs.
* Shops, hotels, libraries, arenas, lairs and the jail get their own colours.
* The map shows only what the game shows you: no rooms in the dark, and hidden exits only
  once you have found them.
* Room numbers are `map * 1000000 + room`, the same from one session to the next, so a saved
  map stays good.

Open the map (**Map** on the toolbar) and walk. Don't also turn on Mudlet's generic mapper
(`start mapping`).

Health, mana and status are in `gmcp.Char.Vitals` and `gmcp.Char.Status` for gauges.
Player guide: https://github.com/jnfisher/silvermere/blob/main/docs/clients.md#mudlet
"""

# A fixed time for every zip entry (the zip format starts at 1980).
ZIP_TIME = (1980, 1, 1, 0, 0, 0)


def lua_field(lua: str, field: str) -> str:
    m = re.search(rf'^M\.{field} = "([^"]+)"', lua, re.MULTILINE)
    if not m:
        sys.exit(f'{LUA.name}: no M.{field} = "..." line')
    return m.group(1)


def lua_string(text: str) -> str:
    """A Lua long string holding `text` (config.lua is read by Mudlet's Lua)."""
    level = 0
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[{text}]{eq}]"


def build_xml(lua: str) -> str:
    return TEMPLATE.format(script=escape(lua))


def build_config(lua: str) -> str:
    version = lua_field(lua, "version")
    released = lua_field(lua, "released")
    return (
        f"mpackage = {lua_string(NAME)}\n"
        f"author = {lua_string(AUTHOR)}\n"
        f"title = {lua_string(TITLE)}\n"
        f"description = {lua_string(DESCRIPTION)}\n"
        f"version = {lua_string(version)}\n"
        f'created = "{released}T00:00:00+00:00"\n'
    )


def build_mpackage(lua: str) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
        for name, text in [
            ("config.lua", build_config(lua)),
            (f"{NAME}.xml", build_xml(lua)),
        ]:
            info = zipfile.ZipInfo(name, date_time=ZIP_TIME)
            info.external_attr = 0o644 << 16
            info.create_system = 3  # unix, whatever system builds it
            z.writestr(info, text.encode("utf-8"))
    return buf.getvalue()


def main() -> int:
    lua = LUA.read_text(encoding="utf-8")
    outputs = [(XML, build_xml(lua).encode("utf-8")), (MPACKAGE, build_mpackage(lua))]
    if "--check" in sys.argv[1:]:
        stale = [p.name for p, data in outputs if not p.exists() or p.read_bytes() != data]
        if stale:
            print(
                f"{', '.join(stale)} out of date: run python3 tools/mudlet/build.py",
                file=sys.stderr,
            )
            return 1
        return 0
    for path, data in outputs:
        path.write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
