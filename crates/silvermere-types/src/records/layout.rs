//! Byte layouts of the Btrieve records: the contract `silvermere-import` decodes with.
//!
//! One [`Layout`] per record type, listing every member (the `unk_*` spans included) with its
//! byte offset and size (bytes 1, 16-bit words 2, 32-bit words 4; byte packed, no padding).
//! `tests/record_sizes.rs` checks every entry against the committed facts.
//!
//! The Worldgroup 3.x build of the same version (the 32-bit module, data files named `*2`)
//! holds the same members, of the same sizes, laid out with 4-byte alignment: each member
//! starts at a multiple of its element size up to 4, and the record is padded to a multiple
//! of its largest member alignment. The `WG_*` layouts are the byte-packed ones with that rule
//! applied, every gap a named `pad_*` member, plus two corrections the data shows: `updrec`
//! aligns its payload to 4 and sizes it for the largest aligned payload (the text block's
//! 2024 bytes), and `actmon`'s 1-byte `inactive` takes 4 bytes, as a realm's records show. [`LayoutSet`] picks the set; `tests/worldgroup_layouts.rs` checks each
//! `WG_*` layout against the rule and the lengths of a Worldgroup realm's files.

/// One member of a record: its name, byte offset, total size and element size.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Field {
    /// The member name, as the decoders and the committed facts use it.
    pub name: &'static str,
    /// Byte offset from the start of the record.
    pub offset: usize,
    /// Total size in bytes (element size times element count).
    pub size: usize,
    /// Size of one element: 1, 2 or 4 (a text array has element size 1).
    pub elem: usize,
}

/// The byte layout of one record type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Layout {
    /// The record type's name, as the decoders and the world export call it.
    pub decoder: &'static str,
    /// Record length in bytes: the length the game opens the data file with.
    pub len: usize,
    /// Every member, in offset order, covering `0..len` without gaps.
    pub fields: &'static [Field],
}

impl Layout {
    /// The member with this name.
    pub fn field(&self, name: &str) -> Option<&'static Field> {
        self.fields.iter().find(|f| f.name == name)
    }
}

/// Which build's record layouts a realm's data files hold.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum LayoutSet {
    /// MajorMUD 1.11p for MajorBBS and Worldgroup 2 (16-bit DOS): byte packed, files named
    /// `WCCUSERS`, `WCCMP001`, ...
    #[default]
    Dos,
    /// The same version built 32-bit for Worldgroup 3.x: 4-byte aligned, files named
    /// `WCCUSER2`, `WCCMP002`, ...
    Worldgroup,
}

impl LayoutSet {
    /// The set's layout of the record type whose byte-packed layout is `dos`.
    ///
    /// # Panics
    ///
    /// When the set has no layout for that record type (the Worldgroup set covers the
    /// 16 record types of the data files, not `permrec`, `evilrec` or `roomkey`).
    pub fn layout(self, dos: &'static Layout) -> &'static Layout {
        match self {
            LayoutSet::Dos => dos,
            LayoutSet::Worldgroup => WORLDGROUP
                .iter()
                .find(|l| l.decoder == dos.decoder)
                .copied()
                .unwrap_or_else(|| panic!("no Worldgroup layout for {}", dos.decoder)),
        }
    }

    /// The set's name, for reports.
    pub fn name(self) -> &'static str {
        match self {
            LayoutSet::Dos => "DOS",
            LayoutSet::Worldgroup => "Worldgroup 3.x",
        }
    }
}

