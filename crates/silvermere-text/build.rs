//! Generates the `Msg` enum from `messages/catalogue.toml` into `OUT_DIR/msg_generated.rs`
//! (included by `src/msg.rs`), so a catalogue key typo is a compile error. The parser is
//! the library's own `src/catalogue.rs`, included by path together with the two modules
//! it validates macro names against.

use std::fmt::Write as _;
use std::path::Path;

// The library modules, compiled into the build script as well. Only the parts the
// generator uses are called, hence the allow.
#[allow(dead_code)]
#[path = "src/ansi.rs"]
mod ansi;
#[allow(dead_code)]
#[path = "src/catalogue.rs"]
mod catalogue;
#[allow(dead_code)]
#[path = "src/colour.rs"]
mod colour;

use catalogue::{ArgType, Entry, TemplatePiece, variant_name};

const CATALOGUE: &str = "messages/catalogue.toml";

fn main() {
    println!("cargo::rerun-if-changed={CATALOGUE}");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/catalogue.rs");
    println!("cargo::rerun-if-changed=src/ansi.rs");
    println!("cargo::rerun-if-changed=src/colour.rs");
    let text =
        std::fs::read_to_string(CATALOGUE).unwrap_or_else(|e| panic!("reading {CATALOGUE}: {e}"));
    let catalogue = match catalogue::parse(&text) {
        Ok(c) => c,
        Err(e) => panic!("{CATALOGUE}: {e}"),
    };
    let code = generate(&catalogue).expect("writing to a String cannot fail");
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("msg_generated.rs");
    std::fs::write(&out, code).unwrap_or_else(|e| panic!("writing {}: {e}", out.display()));
}

/// A catalogue entry with everything the generator derives from it.
struct Prepared<'a> {
    key: &'a str,
    entry: &'a Entry,
    variant: String,
    args: Vec<(String, ArgType)>,
    pieces: Vec<TemplatePiece>,
}

fn generate(catalogue: &catalogue::Catalogue) -> Result<String, std::fmt::Error> {
    let entries: Vec<Prepared> = catalogue
        .messages
        .iter()
        .map(|(key, entry)| Prepared {
            key,
            entry,
            variant: variant_name(key),
            args: entry.arg_list(key).expect("validated by parse"),
            pieces: entry.pieces(key).expect("validated by parse"),
        })
        .collect();

    let mut o = String::new();
    writeln!(o, "// Generated by build.rs from {CATALOGUE}; do not edit.")?;
    writeln!(o)?;
    writeln!(
        o,
        "/// One variant per catalogue entry, generated from `messages/catalogue.toml`."
    )?;
    writeln!(o, "///")?;
    writeln!(o, "/// Each variant's doc shows its template.")?;
    writeln!(o, "#[derive(Debug, Clone, PartialEq, Eq)]")?;
    writeln!(o, "pub enum Msg {{")?;
    for Prepared {
        key,
        entry,
        variant,
        args,
        ..
    } in &entries
    {
        writeln!(o, "    /// `{key}`: `{}`", entry.text.escape_debug())?;
        if let Some(note) = &entry.note {
            writeln!(o, "    ///")?;
            writeln!(o, "    /// {note}")?;
        }
        if args.is_empty() {
            writeln!(o, "    {variant},")?;
        } else {
            let fields: Vec<String> = args
                .iter()
                .map(|(n, t)| format!("{n}: {}", t.rust_name()))
                .collect();
            writeln!(o, "    {variant} {{ {} }},", fields.join(", "))?;
        }
    }
    writeln!(o, "}}")?;
    writeln!(o)?;

    writeln!(o, "impl Msg {{")?;
    // KEYS
    writeln!(o, "    /// Every catalogue key, in catalogue order.")?;
    writeln!(o, "    pub const KEYS: &'static [&'static str] = &[")?;
    for Prepared { key, .. } in &entries {
        writeln!(o, "        {key:?},")?;
    }
    writeln!(o, "    ];")?;
    writeln!(o)?;

    // key()
    writeln!(o, "    /// The catalogue key.")?;
    writeln!(o, "    pub const fn key(&self) -> &'static str {{")?;
    writeln!(o, "        match self {{")?;
    for Prepared {
        key, variant, args, ..
    } in &entries
    {
        writeln!(
            o,
            "            Msg::{variant}{} => {key:?},",
            pattern_suffix(args)
        )?;
    }
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o)?;

    // pattern()
    writeln!(
        o,
        "    /// The pattern registry name the rendered text matches, if any."
    )?;
    writeln!(
        o,
        "    pub const fn pattern(&self) -> Option<&'static str> {{"
    )?;
    writeln!(o, "        match self {{")?;
    for Prepared {
        entry,
        variant,
        args,
        ..
    } in &entries
    {
        match &entry.pattern {
            Some(p) => writeln!(
                o,
                "            Msg::{variant}{} => Some({p:?}),",
                pattern_suffix(args)
            )?,
            None => writeln!(
                o,
                "            Msg::{variant}{} => None,",
                pattern_suffix(args)
            )?,
        }
    }
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o)?;

    // wrap()
    writeln!(
        o,
        "    /// The wrap width the original applied (the host's word wrap, `btutsw`), or `None`."
    )?;
    writeln!(o, "    pub const fn wrap(&self) -> Option<u8> {{")?;
    writeln!(o, "        match self {{")?;
    for Prepared {
        entry,
        variant,
        args,
        ..
    } in &entries
    {
        let w = if entry.wrap {
            "Some(crate::wrap::WRAPCOLS)"
        } else {
            "None"
        };
        writeln!(
            o,
            "            Msg::{variant}{} => {w},",
            pattern_suffix(args)
        )?;
    }
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o)?;

    // pieces()
    writeln!(
        o,
        "    /// The template as pieces: text, resolved ANSI strings, argument slots and"
    )?;
    writeln!(o, "    /// colour rows.")?;
    writeln!(o, "    pub const fn pieces(&self) -> &'static [Piece] {{")?;
    writeln!(o, "        match self {{")?;
    for Prepared {
        variant,
        args,
        pieces,
        ..
    } in &entries
    {
        writeln!(
            o,
            "            Msg::{variant}{} => &[",
            pattern_suffix(args)
        )?;
        for piece in pieces {
            match piece {
                TemplatePiece::Text(t) => writeln!(o, "                Piece::Text({t:?}),")?,
                TemplatePiece::Ansi(name) => {
                    writeln!(o, "                Piece::Ansi(crate::ansi::{name}),")?
                }
                TemplatePiece::Arg(name) => {
                    let index = args
                        .iter()
                        .position(|(n, _)| n == name)
                        .expect("args come from the pieces");
                    writeln!(o, "                Piece::Arg({index}),")?;
                }
                TemplatePiece::Colour(row) => {
                    writeln!(
                        o,
                        "                Piece::Colour(crate::colour::ColRow::{row:?}),"
                    )?;
                }
            }
        }
        writeln!(o, "            ],")?;
    }
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o)?;

    // write_arg()
    writeln!(
        o,
        "    /// Appends argument `index` (a `Piece::Arg` slot) to `out`."
    )?;
    writeln!(
        o,
        "    pub fn write_arg(&self, index: usize, out: &mut String) {{"
    )?;
    writeln!(o, "        use std::fmt::Write as _;")?;
    writeln!(o, "        match (self, index) {{")?;
    for Prepared { variant, args, .. } in &entries {
        for (i, (name, _)) in args.iter().enumerate() {
            writeln!(
                o,
                "            (Msg::{variant} {{ {name}, .. }}, {i}) => {{ let _ = write!(out, \"{{{name}}}\"); }}"
            )?;
        }
    }
    writeln!(o, "            _ => {{}}")?;
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o)?;

    // examples()
    writeln!(
        o,
        "    /// One message per catalogue entry, built with the catalogue's example"
    )?;
    writeln!(
        o,
        "    /// arguments (a missing example gives an empty string, 0 or `'?'`)."
    )?;
    writeln!(o, "    pub fn examples() -> Vec<Msg> {{")?;
    writeln!(o, "        vec![")?;
    for Prepared {
        entry,
        variant,
        args,
        ..
    } in &entries
    {
        if args.is_empty() {
            writeln!(o, "            Msg::{variant},")?;
        } else {
            let fields: Vec<String> = args
                .iter()
                .map(|(name, ty)| {
                    let value = entry.example.get(name).map(String::as_str);
                    format!("{name}: {}", example_literal(*ty, value))
                })
                .collect();
            writeln!(o, "            Msg::{variant} {{ {} }},", fields.join(", "))?;
        }
    }
    writeln!(o, "        ]")?;
    writeln!(o, "    }}")?;
    writeln!(o, "}}")?;
    Ok(o)
}

/// `{ .. }` for a struct variant, nothing for a unit variant.
fn pattern_suffix(args: &[(String, ArgType)]) -> &'static str {
    if args.is_empty() { "" } else { " { .. }" }
}

/// The Rust literal for an example value.
fn example_literal(ty: ArgType, value: Option<&str>) -> String {
    match (ty, value) {
        (ArgType::String, v) => format!("{:?}.to_string()", v.unwrap_or("")),
        (ArgType::Char, Some(v)) => format!("{:?}", v.chars().next().expect("validated: one char")),
        (ArgType::Char, None) => "'?'".to_string(),
        (ty, Some(v)) => format!("{v}{}", ty.rust_name()),
        (ty, None) => format!("0{}", ty.rust_name()),
    }
}
