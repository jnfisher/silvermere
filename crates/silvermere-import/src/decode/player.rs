/// The schema's character; `lastdate` and `deathdate` (DOS dates) in `clock`'s zone.
pub fn to_character(r: &PlayerRecord, clock: &LegacyClock) -> Result<Character, DecodeError> {
    let key = format!("userid {}", r.userid.trimmed());
    let lastdate = clock.at("player", &key, "lastdate", r.lastdate, 0)?;
    let deathdate = clock.at("player", &key, "deathdate", r.deathdate, 0)?;
    Ok(Character {
        userid: r.userid.trimmed(),
        firstname: r.firstname.trimmed(),
        lastname: r.lastname.trimmed(),
        exp: r.exp,
        spells: r.spells.map(|s| SpellNo(s as i16)),
        spellvals: r.spellvals,
        spellrnds: r.spellrnds,
        title: r.title.trimmed(),
        race: RaceNo(r.race),
        class: ClassNo(r.class),
        level: r.level,
        basint: r.basint,
        baswil: r.baswil,
        basstr: r.basstr,
        bashea: r.bashea,
        basagi: r.basagi,
        bascha: r.bascha,
        intel: r.intel,
        wil: r.wil,
        str: r.str,
        hea: r.hea,
        agi: r.agi,
        cha: r.cha,
        maxhp: r.maxhp,
        hp: r.hp,
        maxwgt: r.maxwgt,
        wgt: r.wgt,
        maxenergy: r.maxenergy,
        energy: r.energy,
        poison: r.poison,
        maxmr: r.maxmr,
        mr: r.mr,
        map: MapId(r.map as u32),
        room: RoomId(r.room as u32),
        light: r.light,
        hunger: r.hunger,
        thirst: r.thirst,
        ninvslots: r.ninvslots,
        items: r.items.iter().copied().map(ItemNo).collect(),
        itemuses: r.itemuses.to_vec(),
        nkeyslots: r.nkeyslots,
        keys: r.keys.iter().copied().map(ItemNo).collect(),
        keyuses: r.keyuses.to_vec(),
        qflags2: r.qflags2,
        hpbonus: r.hpbonus,
        manabonus: r.manabonus,
        expbil: r.expbil,
        exprem: r.exprem,
        nspellslots: r.nspellslots,
        spellbook: r.spellbook.iter().copied().map(SpellNo).collect(),
        evil: r.evil,
        lawful: r.lawful,
        trailmaps: r.trailmaps.map(|m| MapId(m as u32)),
        trailrooms: r.trailrooms.map(|m| RoomId(m as u32)),
        verbose: r.verbose,
        bchannel: r.bchannel,
        fasttalk: r.fasttalk,
        statline: StatlineMode::from_code(u16::from(r.statline)),
        hidden: r.hidden,
        perception: r.perception,
        stealth: r.stealth,
        martial: r.martial,
        thievery: r.thievery,
        maxmana: r.maxmana,
        mana: r.mana,
        spellcast: r.spellcast,
        traps: r.traps,
        disarm: r.disarm,
        picklocks: r.picklocks,
        tracking: r.tracking,
        coins: coins_named(r.runic, r.platinum, r.gold, r.silver, r.copper),
        weapon: ItemNo(r.weapon),
        worn: r.worn.map(ItemNo),
        wornuses: r.wornuses,
        autoengage: r.autoengage,
        lives: r.lives,
        aided: r.aided,
        rank: r.rank,
        lighttime: r.lighttime,
        readied: r.readied,
        delay: r.delay,
        roomlight: r.roomlight,
        gang: r.gang.trimmed(),
        hairlen: r.hairlen,
        haircol: r.haircol,
        eyecol: r.eyecol,
        paging: r.paging,
        cp: r.cp,
        suicpw: r.suicpw.trimmed(),
        attackers: r.attackers,
        status: PlayerStatus::from_bits_retain(r.status),
        movedir: r.movedir,
        dragging: r.dragging,
        totalcp: r.totalcp,
        immortal: r.immortal,
        pagecnt: r.pagecnt,
        pagemax: r.pagemax,
        settings: PlayerSettings::from_bits_retain(r.settings),
        gossmax: r.gossmax,
        auctmax: r.auctmax,
        gosscnt: r.gosscnt,
        auctcnt: r.auctcnt,
        encumpct: r.encumpct,
        avbonus: r.avbonus,
        acbonus: r.acbonus,
        dmgbonus: r.dmgbonus,
        mabase: r.mabase,
        arenahp: r.arenahp,
        qflags: r.qflags,
        version: r.version,
        msglevel: MessageLevel::from_code(u16::from(r.msglevel)),
        pvpcnt: r.pvpcnt,
        randomhp: r.randomhp,
        abils: abilities(&r.abils, &r.abilvals),
        resttick: r.resttick,
        critbonus: r.critbonus,
        drbonus: r.drbonus,
        drpct: r.drpct,
        energyuse: r.energyuse,
        shield: r.shield,
        defmod: r.defmod,
        // half-minutes since the last cleanup (one more per slow cycle)
        sesstime: u32::from(r.sesstime as u16),
        lifemins: r.lifemins,
        moves: r.moves,
        lastdate,
        status2: PlayerStatus2::from_bits_retain(r.status2),
        palette: r.palette,
        deathdate,
        flags: PlayerFlags::from_bits_retain(r.flags),
        sex: r.sex,
        healrate: r.healrate,
        manarate: r.manarate,
        racechg: r.racechg,
        lastmon: r.lastmon,
        lastmoncnt: r.lastmoncnt,
        pvptimer: r.pvptimer,
        medtick: r.medtick,
    })
}
